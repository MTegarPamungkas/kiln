import 'dart:convert';
import 'dart:io';

import 'package:kiln_extension_sdk/kiln_extension_sdk.dart';
import 'package:mason/mason.dart';
import 'package:path/path.dart' as p;

Future<void> main(List<String> arguments) async {
  final check = arguments.contains('--check');
  final root = Directory.current;
  final outputs = <({String path, String content})>[];

  final appBasic = createBundle(
    Directory(p.join(root.path, 'bricks', 'app_basic')),
  );
  outputs.add((
    path: 'packages/kiln_cli/lib/src/bundles/app_basic_bundle.dart',
    content: _bundleFile(
      imports: const <String>['dart:convert', 'package:mason/mason.dart'],
      variable: 'appBasicBundle',
      bundle: appBasic,
      isExtension: false,
    ),
  ));

  final extensionTemplate = createBundle(
    Directory(p.join(root.path, 'bricks', 'extension_template')),
  );
  outputs.add((
    path: 'packages/kiln_cli/lib/src/bundles/extension_template_bundle.dart',
    content: _bundleFile(
      imports: const <String>['dart:convert', 'package:mason/mason.dart'],
      variable: 'extensionTemplateBundle',
      bundle: extensionTemplate,
      isExtension: false,
    ),
  ));

  final extensionDirs =
      Directory(p.join(root.path, 'extensions'))
          .listSync()
          .whereType<Directory>()
          .where(
            (directory) =>
                File(p.join(directory.path, 'extension.yaml')).existsSync(),
          )
          .toList(growable: false)
        ..sort((left, right) => left.path.compareTo(right.path));

  final catalogImports = <String>[];
  final catalogVariables = <String>[];
  for (final directory in extensionDirs) {
    final id = p.basename(directory.path);
    final manifest = ExtensionManifest.parse(
      File(p.join(directory.path, 'extension.yaml')).readAsStringSync(),
      rootPath: directory.path,
    );
    final bundle = createBundle(Directory(p.join(directory.path, 'brick')));
    final variable = '${_camel(id)}Extension';
    catalogImports.add("import '${id}_bundle.dart';");
    catalogVariables.add('  $variable,');
    outputs.add((
      path: 'packages/kiln_cli/lib/src/bundles/${id}_bundle.dart',
      content: _bundleFile(
        imports: const <String>[
          'dart:convert',
          'package:kiln_extension_sdk/kiln_extension_sdk.dart',
          'package:mason/mason.dart',
        ],
        variable: variable,
        bundle: bundle,
        isExtension: true,
        manifest: manifest,
        docs: _documentation(directory),
      ),
    ));
  }

  outputs.add((
    path: 'packages/kiln_cli/lib/src/bundles/catalog.g.dart',
    content: _catalogFile(catalogImports, catalogVariables),
  ));

  var changed = false;
  for (final output in outputs) {
    final file = File(p.join(root.path, output.path));
    if (check) {
      final current = file.existsSync() ? file.readAsStringSync() : '';
      if (current != output.content) {
        changed = true;
        stderr.writeln('out of date: ${output.path}');
      }
      continue;
    }
    file.parent.createSync(recursive: true);
    file.writeAsStringSync(output.content);
    stdout.writeln('wrote ${output.path}');
  }

  if (check && changed) {
    exitCode = 1;
  }
}

String _bundleFile({
  required List<String> imports,
  required String variable,
  required MasonBundle bundle,
  required bool isExtension,
  ExtensionManifest? manifest,
  Map<String, List<int>> docs = const <String, List<int>>{},
}) {
  final encodedBundle = base64.encode(utf8.encode(jsonEncode(bundle.toJson())));
  final importBlock = imports.map((entry) => "import '$entry';").join('\n');
  if (!isExtension) {
    return '''
// GENERATED CODE - DO NOT MODIFY BY HAND.
// Generated by tool/bundle.dart from bricks/.
$importBlock

final MasonBundle $variable = MasonBundle.fromJson(
  (jsonDecode(utf8.decode(base64Decode(
    '$encodedBundle',
  ))) as Map<Object?, Object?>).cast<String, dynamic>(),
);
''';
  }

  final encodedManifest = base64.encode(utf8.encode(jsonEncode(manifest!.raw)));
  final docsBlock = docs.entries
      .map(
        (entry) =>
            "    '${entry.key}': base64Decode(\n"
            "      '${base64.encode(entry.value)}',\n"
            '    ),\n',
      )
      .join();
  final docsArgument = docs.isEmpty
      ? ''
      : '  docs: <String, List<int>>{\n$docsBlock  },\n';
  return '''
// GENERATED CODE - DO NOT MODIFY BY HAND.
// Generated by tool/bundle.dart from extensions/$variable.
$importBlock

final AvailableExtension $variable = AvailableExtension(
  manifest: ExtensionManifest.fromMap(
    (jsonDecode(utf8.decode(base64Decode(
      '$encodedManifest',
    ))) as Map<Object?, Object?>).cast<String, Object?>(),
  ),
  bundle: MasonBundle.fromJson(
    (jsonDecode(utf8.decode(base64Decode(
      '$encodedBundle',
    ))) as Map<Object?, Object?>).cast<String, dynamic>(),
  ),
$docsArgument  source: ExtensionSource.bundled,
);
''';
}

/// Extension documentation embedded into the generated bundle: `README.md`
/// and everything under `docs/`, keyed by path relative to the extension
/// root. Copied verbatim so installed apps carry the extension's feature
/// docs without visiting the source repository.
Map<String, List<int>> _documentation(Directory root) {
  final files = <String, List<int>>{};
  final readme = File(p.join(root.path, 'README.md'));
  if (readme.existsSync()) {
    files['README.md'] = readme.readAsBytesSync();
  }
  final docs = Directory(p.join(root.path, 'docs'));
  if (!docs.existsSync()) {
    return files;
  }
  final docFiles =
      docs.listSync(recursive: true).whereType<File>().toList()
        ..sort((left, right) => left.path.compareTo(right.path));
  for (final doc in docFiles) {
    final relative = p
        .relative(doc.path, from: root.path)
        .replaceAll('\\', '/');
    files['docs/$relative'] = doc.readAsBytesSync();
  }
  return files;
}

String _catalogFile(List<String> imports, List<String> variables) {
  return '''
// GENERATED CODE - DO NOT MODIFY BY HAND.
// Generated by tool/bundle.dart from extensions/.
// ignore_for_file: directives_ordering

import 'package:kiln_extension_sdk/kiln_extension_sdk.dart';
${imports.join('\n')}

final List<AvailableExtension> bundledExtensions = <AvailableExtension>[
${variables.join('\n')}
];
''';
}

String _camel(String value) {
  final parts = value
      .split(RegExp(r'[_\s-]+'))
      .where((part) => part.isNotEmpty);
  final buffer = StringBuffer();
  var first = true;
  for (final part in parts) {
    if (first) {
      buffer.write(part);
      first = false;
    } else {
      buffer
        ..write(part[0].toUpperCase())
        ..write(part.substring(1));
    }
  }
  return buffer.toString();
}
